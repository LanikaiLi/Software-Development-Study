// While Loop
let count = 0

while (count < 3) {
    console.log("Count is: " + count)
    count++
}

// For Loop
for (let i = 0; i < 3; i++) {
    console.log("Index is: " + i)
}

// forEach Loop
let fruits = ["banana", "kiwi", "lemon"]

fruits.forEach(function(fruit) {
    //console.log("I'm eating a " + fruit + ".")
    console.log("I'm eating a ${fruit}.")
})

